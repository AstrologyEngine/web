import { readdir, readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
const dir = "static/atlas";
const hash = (bytes: Uint8Array | string) =>
  createHash("sha256").update(bytes).digest("hex");
const shards: Record<string, { sha256: string; bytes: number }> = {};
for (const name of (await readdir(dir))
  .filter((name) => name.endsWith(".bin"))
  .sort()) {
  const data = await readFile(`${dir}/${name}`);
  shards[name] = { sha256: hash(data), bytes: data.length };
}
const manifest =
  JSON.stringify(
    {
      schemaVersion: 1,
      source: "GeoNames",
      license: "https://creativecommons.org/licenses/by/4.0/",
      shards,
    },
    null,
    2,
  ) + "\n";
await writeFile(`${dir}/manifest.json`, manifest);
await writeFile(
  "src/lib/server/birth/atlas-manifest.ts",
  `// Generated by scripts/birth/manifest.ts from the shipped atlas.\nexport const atlasManifest = ${manifest.trimEnd()} as const;\nexport const atlasHash = '${hash(manifest)}';\n`,
);
